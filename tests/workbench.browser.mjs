// These fixtures use the production bundle with a simulated DSH adapter.
async function createTemplate(page,name,heading){
 await page.getByRole("button",{name:"管理工作台"}).click()
 await page.getByRole("button",{name:new RegExp(name)}).click()
 await page.getByRole("button",{name:"运行预览"}).click()
 await expect(frame(page).getByRole("heading",{name:heading,exact:true})).toBeVisible()
 await expect(page.getByRole("button",{name:"发布生效"})).toBeEnabled()
 await page.getByRole("button",{name:"发布生效"}).click()
 await expect(frame(page).getByRole("heading",{name:heading,exact:true})).toBeVisible()
}
async function noOverflow(page){
 const html=frame(page).locator("#app")
 expect(await html.evaluate(el=>el.scrollWidth<=el.clientWidth+2)).toBeTruthy()
}
async function setTheme(page,dark){
 await page.evaluate(dark=>{
  const root=document.documentElement
  root.style.colorScheme=dark?"dark":"light"
  document.body.toggleAttribute("data-ds-dark-theme",dark)
  const values=dark?{bg:"#24252b",fg:"#e8e9ed",muted:"#363740",border:"#484a54",secondary:"#a7a9b2",primary:"#e8e9ed",primaryFg:"#24252b",popover:"#303139"}:{bg:"#ffffff",fg:"#202128",muted:"#f1f2f4",border:"#d8dae0",secondary:"#646872",primary:"#202128",primaryFg:"#ffffff",popover:"#ffffff"}
  for(const [k,v] of Object.entries({"bg-layer-1":values.bg,"label-primary":values.fg,"button-ghost-active-fill":values.muted,"border-l4":values.border,"label-secondary":values.secondary,"button-primary-fill":values.primary,"label-primary-foreground":values.primaryFg,"bg-layer-3":values.popover}))root.style.setProperty("--dsw-alias-"+k,v)
 },dark)
 await expect(frame(page).locator("html")).toHaveCSS("color-scheme",dark?"dark":"light")
}
test("general template uses scoped accessible select and responsive layout",async({page},testInfo)=>{
 await page.goto("/")
 await expect(frame(page).getByRole("heading",{name:"今天做什么？"})).toBeVisible()
 const trigger=frame(page).getByRole("combobox",{name:"工作区",exact:true})
 await trigger.click()
 await expect(frame(page).getByRole("option",{name:"验收项目"})).toBeVisible()
 await frame(page).getByRole("option",{name:"验收项目"}).click()
 await expect(trigger).toContainText("验收项目")
 await frame(page).getByRole("textbox",{name:"工作需求"}).fill("测试工作")
 await frame(page).getByRole("button",{name:"打开对话"}).click()
 await expect.poll(()=>page.evaluate(()=>window.__calls.some(c=>c[0]==="start"&&c[1]==="w1"&&c[2]?.prompt==="测试工作"))).toBeTruthy()
 await page.getByRole("combobox",{name:"切换工作台"}).click()
 await expect(page.getByRole("option",{name:/通用工作台/})).toBeVisible()
 await page.keyboard.press("Escape")
 await expect(page.getByRole("option",{name:/通用工作台/})).toHaveCount(0)
 await setTheme(page,false)
 await page.screenshot({path:testInfo.outputPath("general-light.png")})
 await setTheme(page,true)
 await page.screenshot({path:testInfo.outputPath("general-dark.png")})
 await page.setViewportSize({width:520,height:720})
 await noOverflow(page)
 await page.screenshot({path:testInfo.outputPath("general-narrow.png")})
})
