import {test,expect} from "@playwright/test"
const frame=page=>page.frameLocator("iframe")
test("built-in page displays real adapter data and opens host session",async({page})=>{
 await page.goto("/")
 await expect(frame(page).getByRole("heading",{name:"今天做什么？"})).toBeVisible()
 await expect(frame(page).getByText("经营数据核对").first()).toBeVisible()
 await frame(page).getByText("经营数据核对").first().click()
 expect(await page.evaluate(()=>window.__calls.some(c=>c[0]==="open"&&c[1]==="s1"))).toBeTruthy()
})
test("AI response becomes a draft, preview is isolated, publication persists",async({page})=>{
 await page.goto("/")
 await expect(frame(page).getByRole("heading",{name:"今天做什么？"})).toBeVisible()
 await page.getByRole("button",{name:"定制",exact:true}).click()
 await page.getByPlaceholder("例如：新增一个月末倒计时组件").fill("新增计数")
 await page.getByRole("button",{name:"在 DSH 中请 AI 修改"}).click()
 await page.getByRole("button",{name:"导入 AI 最新结果"}).click()
 await expect(page.getByLabel("工作台源码（TSX）")).toHaveValue(/AI 定制结果/)
 await page.getByRole("button",{name:"运行预览"}).click()
 await expect(frame(page).getByRole("heading",{name:"AI 定制结果"})).toBeVisible()
 await frame(page).getByRole("button",{name:"计数：0"}).click()
 await expect(frame(page).getByRole("button",{name:"计数：1"})).toBeVisible()
 await expect(page.getByRole("button",{name:"发布生效"})).toBeEnabled()
 await page.getByRole("button",{name:"发布生效"}).click()
 await expect(frame(page).getByRole("button",{name:"计数：0"})).toBeVisible()
 await frame(page).getByRole("button",{name:"计数：0"}).click()
 await expect(frame(page).getByRole("button",{name:"计数：1"})).toBeVisible()
 await page.reload()
 await expect(frame(page).getByRole("button",{name:"计数：1"})).toBeVisible()
})
